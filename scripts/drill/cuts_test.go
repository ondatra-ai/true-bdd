func TestCutsKeepOnlySpecifiedLayersAndNoHistory(t *testing.T) {
	runner, record := fixture(t)
	for _, name := range []string{"a", "b", "c", "d"} {
		cut, err := runner.Cut(t.Context(), record.Directory, name)
		must(t, err)

		t.Cleanup(func() { _ = os.RemoveAll(cut.Directory) })
		files := strings.Split(git(t, cut.Directory, "ls-files"), "\n")

		expected := expectedCutFiles(name)

		slices.Sort(expected)
		slices.Sort(files)

		if !slices.Equal(files, expected) {
			t.Fatalf("cut %s files: %v; want %v", name, files, expected)
		}

		if count := git(t, cut.Directory, "rev-list", "--count", "--all"); count != "1" {
			t.Fatalf("history: %s", count)
		}

		if strings.HasPrefix(cut.Directory, record.Directory) || strings.HasPrefix(cut.Directory, runner.Root) {
			t.Fatal("cut not isolated")
		}
	}

	capture, err := os.ReadFile(os.Getenv("DRILL_CAPTURE"))
	must(t, err)

	if !strings.Contains(string(capture), "-trimpath") {
		t.Fatal("build did not trim paths")
	}
}

func expectedCutFiles(name string) []string {
	expected := []string{".gitignore",
		"go.mod",
		"go.sum",
		testProduct,
		"docs/architecture/architecture.yaml",
		"docs/scenarios.yaml",
		"true-bdd/config.yaml",
		"templates/fix.md",
		testChannel,
		"scripts/tool.go",
		"tests/true-bdd/coverage_test.go",
		"tests/true-bdd/scenarios/scenarios.go"}
	if name == "a" {
		expected = append(expected, "tests/true-bdd/generated_test.go", "tests/true-bdd/steps/steps.go")
	}

	if name != "d" {
		expected = append(expected, "tests/true-bdd/fixtures/example/input/project.yaml")
	}

	if name == "a" || name == "b" {
		expected = append(expected, "tests/true-bdd/fixtures/example/cassettes/golden.json")
	}

	return expected
}

// Every cut keeps what concepts need, unchanged: the product document's
// concepts and glossary, the architecture's bindings and Word mappings, and
// the Public interface document the bindings reference (#259).
func TestEveryCutKeepsTheDocumentsConceptsNeed(t *testing.T) {
	documents := map[string]string{
		testProduct: "concepts:\n  when:\n    - {concept: doubling, means: The Owner doubles a number., terms: [number]}\n" +
			"glossary:\n  - {term: number, means: A whole number.}\n",
		interfaceArchitecture: "architecture:\n  services:\n    - path: services/true-bdd\n    - name: calc\n" +
			"      public_interface: {kind: cli, document: docs/architecture/calc-cli.yaml}\n" +
			"  terms:\n    - {term: number, technical: The double argument., observed_by: Its stdout.}\n" +
			"  concepts:\n    - {concept: doubling, block: when, service: calc, references: [{command: double}], " +
			"does: Run double.}\n",
		"docs/architecture/calc-cli.yaml": "opencli: 0.1\ncommands: {double: {}}\n",
	}

	runner, record := fixtureEngineFiles(t, "#!/bin/sh\nexit 0\n", documents)
	for _, name := range []string{"a", "b", "c", "d"} {
		cut, err := runner.Cut(t.Context(), record.Directory, name)
		must(t, err)
		t.Cleanup(func() { _ = os.RemoveAll(cut.Directory) })

		for path, want := range documents {
			data, err := os.ReadFile(filepath.Join(cut.Directory, path))
			if err != nil || string(data) != want {
				t.Fatalf("cut %s lost or changed %s, which concepts need: %q, %v", name, path, data, err)
			}
		}
	}
}
