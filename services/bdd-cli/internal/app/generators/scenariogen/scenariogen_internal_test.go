// Writing is idempotent, so a regeneration that changed nothing touches
// no mtime — which is what a build cache and a file watcher key on.
func TestWriteIsIdempotent(t *testing.T) {
	t.Parallel()

	plan, root := planOne(t, scenario("E2E-001", testFile))

	written, err := Write(plan, root)
	if err != nil {
		t.Fatalf("Write: %v", err)
	}

	if len(written) != 1 {
		t.Fatalf("want one file written, got %v", written)
	}

	written, err = Write(plan, root)
	if err != nil {
		t.Fatalf("Write again: %v", err)
	}

	if len(written) != 0 {
		t.Errorf("want nothing rewritten, got %v", written)
	}

	drifted, err := Verify(plan, root)
	if err != nil {
		t.Fatalf("Verify: %v", err)
	}

	if len(drifted) != 0 {
		t.Errorf("want no drift after writing, got %v", drifted)
	}
}

// A typo'd `path:` pointing at a step definition must not delete it.
func TestWriteRefusesToClobberAHandWrittenFile(t *testing.T) {
	t.Parallel()

	plan, root := planOne(t, scenario("E2E-001", testFile))

	target := filepath.Join(root, filepath.FromSlash(testFile))

	err := disk.Write(target, []byte("package steps\n\n// hand written\n"), disk.Shared)
	if err != nil {
		t.Fatalf("seed: %v", err)
	}

	_, err = Write(plan, root)
	if !errors.Is(err, ErrWouldClobberHandWritten) {
		t.Fatalf("want ErrWouldClobberHandWritten, got %v", err)
	}

	after, err := disk.Read(target)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}

	if !strings.Contains(string(after), "hand written") {
		t.Error("the hand-written file was overwritten")
	}
}

// A missing file and a stale one are both drift, and each says which.
func TestVerifyReportsMissingAndStale(t *testing.T) {
	t.Parallel()

	plan, root := planOne(t, scenario("E2E-001", testFile))

	drifted, err := Verify(plan, root)
	if err != nil {
		t.Fatalf("Verify: %v", err)
	}

	if len(drifted) != 1 || !strings.Contains(drifted[0].Reason, "no generated test file") {
		t.Fatalf("want a missing-file drift, got %v", drifted)
	}

	_, err = Write(plan, root)
	if err != nil {
		t.Fatalf("Write: %v", err)
	}

	target := filepath.Join(root, filepath.FromSlash(testFile))

	source, err := disk.Read(target)
	if err != nil {
		t.Fatalf("read: %v", err)
	}

	err = disk.Write(target, append(source, byte('\n')), disk.Shared)
	if err != nil {
		t.Fatalf("perturb: %v", err)
	}

	drifted, err = Verify(plan, root)
	if err != nil {
		t.Fatalf("Verify again: %v", err)
	}

	if len(drifted) != 1 || !strings.Contains(drifted[0].Reason, "not what the registry renders") {
		t.Fatalf("want a stale-file drift, got %v", drifted)
	}
}

