const (
	suiteName    = "bdd-cli"
	webSuite     = "bdd-web"
	suitePath    = "tests/bdd-cli"
	testFile     = "tests/bdd-cli/build_code_test.go"
	registryPath = "docs/scenarios.yaml"
)

// arch is a spec declaring both services on go-test. There are no suites:
// a scenario's own service and path place its generated file.
func arch() *architecture.Architecture {
	return &architecture.Architecture{
		Testing: architecture.Testing{Framework: FrameworkGoTest},
		Services: []architecture.Service{
			{Name: suiteName, Path: "services/bdd-cli", Language: "go"},
			{Name: webSuite, Path: "services/bdd-web", Language: "typescript"},
		},
	}
}

// scenario builds one registry entry with a single Given step.
func scenario(id, path string) *registry.RegistryScenario {
	return &registry.RegistryScenario{
		ID: id, Description: "one", Service: suiteName, Path: path,
		Statements: []registry.Statement{{Keyword: registry.KeywordGiven, Text: "a tree"}},
	}
}

// repoWithModule returns a temp dir holding a go.mod, so the import path
// of a suite's shim can be computed.
func repoWithModule(t *testing.T) string {
	t.Helper()

	root := t.TempDir()

	err := disk.Write(filepath.Join(root, "go.mod"), []byte("module example.com/repo\n"), disk.Shared)
	if err != nil {
		t.Fatalf("write go.mod: %v", err)
	}

	err = disk.Dir(filepath.Join(root, suitePath), disk.Shared)
	if err != nil {
		t.Fatalf("create suite dir: %v", err)
	}

	return root
}

// planOne builds a plan for a single scenario, failing the test on any
// refusal.
func planOne(t *testing.T, item *registry.RegistryScenario) (*Plan, string) {
	t.Helper()

	root := repoWithModule(t)

	plan, err := BuildPlan([]*registry.RegistryScenario{item}, arch(), root, registryPath)
	if err != nil {
		t.Fatalf("BuildPlan: %v", err)
	}

	return plan, root
}

// The ordinary case: a scenario renders a compiling Go test that names
// itself, imports the suite's shim, and states its steps as literals.
func TestRenderEmitsAGeneratedTest(t *testing.T) {
	t.Parallel()

	plan, _ := planOne(t, scenario("E2E-001", testFile))

	source, err := Render(plan.Files[0])
	if err != nil {
		t.Fatalf("Render: %v", err)
	}

	for _, want := range []string{
		"//go:build bdd",
		"// Code generated by `true-bdd build tests`. DO NOT EDIT.",
		"package bddcli_test",
		`"example.com/repo/tests/bdd-cli/scenarios"`,
		`func TestE2E001(t *testing.T) {`,
		`s := scenarios.New(t, "E2E-001")`,
		"s.Given(`a tree`)",
		"s.Done()",
	} {
		if !strings.Contains(string(source), want) {
			t.Errorf("rendered file is missing %q:\n%s", want, source)
		}
	}
}

// Step text is a raw string so the "quoted" runs and regex escapes a
// scenario is full of survive unescaped — that is what keeps the file
// reading like the scenario it transcribes.
func TestRenderPrefersRawStringLiterals(t *testing.T) {
	t.Parallel()

	item := scenario("E2E-001", testFile)
	item.Statements[0].Text = `stdout matches level=ERROR msg="Refusing to start" \(x\)`

	plan, _ := planOne(t, item)

	source, err := Render(plan.Files[0])
	if err != nil {
		t.Fatalf("Render: %v", err)
	}

	want := "s.Given(`" + item.Statements[0].Text + "`)"
	if !strings.Contains(string(source), want) {
		t.Errorf("want the raw literal %q:\n%s", want, source)
	}
}

// A backtick makes a raw string impossible, so the quoted form takes
// over rather than emitting source Go would not parse.
func TestLiteralFallsBackToQuotingOnABacktick(t *testing.T) {
	t.Parallel()

	got := literal("stdout matches `true-bdd build tests`")

	want := `"stdout matches ` + "`" + `true-bdd build tests` + "`" + `"`
	if got != want {
		t.Errorf("literal() = %s, want %s", got, want)
	}
}

// Two scenarios sharing a path land in one file, in id order — not the
// document's order, which a YAML map decode has already lost.
func TestBuildPlanGroupsByPathInIDOrder(t *testing.T) {
	t.Parallel()

	root := repoWithModule(t)

	plan, err := BuildPlan([]*registry.RegistryScenario{
		scenario("E2E-002", testFile),
		scenario("E2E-001", testFile),
	}, arch(), root, registryPath)
	if err != nil {
		t.Fatalf("BuildPlan: %v", err)
	}

	if len(plan.Files) != 1 {
		t.Fatalf("want one file, got %d", len(plan.Files))
	}

	ids := []string{plan.Files[0].Scenarios[0].ID, plan.Files[0].Scenarios[1].ID}
	if ids[0] != "E2E-001" || ids[1] != "E2E-002" {
		t.Errorf("want id order, got %v", ids)
	}
}

// Everything a `path:` can be wrong about, refused by name: each produces a
// file that compiles into the wrong package, overwrites something it must
// not, or does not compile at all — so none of them can be a warning.
func TestBuildPlanRefusesABadPath(t *testing.T) {
	t.Parallel()

	cases := map[string]struct {
		path string
		want error
	}{
		"absent":          {"", ErrNoPath},
		"absolute":        {"/tmp/x_test.go", ErrPathNotRelative},
		"escaping":        {"../x_test.go", ErrPathNotRelative},
		"not a test file": {"tests/bdd-cli/x.go", ErrPathNotTestFile},
	}

	for name, testCase := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			root := repoWithModule(t)

			_, err := BuildPlan([]*registry.RegistryScenario{
				scenario("E2E-001", testCase.path),
			}, arch(), root, registryPath)

			if !errors.Is(err, testCase.want) {
				t.Fatalf("want %v, got %v", testCase.want, err)
			}
		})
	}
}

