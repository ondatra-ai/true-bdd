package scenariogen

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/ondatra-ai/true-bdd/services/true-bdd/internal/infrastructure/disk"
)

const legacyScenariosDir = "scenarios"

// RemoveLegacyWiring removes only marked files of the retired intermediate package.
func RemoveLegacyWiring(plan *Plan, root string) error {
	seen := make(map[string]bool)

	for _, file := range plan.Files {
		dir := filepath.Join(root, filepath.Dir(file.Path), legacyScenariosDir)
		if seen[dir] {
			continue
		}

		seen[dir] = true

		err := removeLegacyDirectory(dir)
		if err != nil {
			return err
		}
	}

	return nil
}

func removeLegacyDirectory(dir string) error {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}

	if err != nil {
		return fmt.Errorf("read legacy suite package: %w", err)
	}

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}

		name := filepath.Join(dir, entry.Name())

		err = removeLegacyFile(name)
		if err != nil {
			return err
		}
	}

	entries, err = os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("read legacy suite package: %w", err)
	}

	if len(entries) == 0 {
		err = disk.Remove(dir)
		if err != nil {
			return fmt.Errorf("remove empty legacy package: %w", err)
		}
	}

	return nil
}

func removeLegacyFile(name string) error {
	source, err := disk.Read(name)
	if err != nil {
		return fmt.Errorf("read legacy suite source: %w", err)
	}

	if hasGeneratedMarker(source) && strings.Contains(string(source), "Code generated by true-bdd build steps.") {
		err = disk.Remove(name)
		if err != nil {
			return fmt.Errorf("remove legacy suite source: %w", err)
		}
	}

	return nil
}
