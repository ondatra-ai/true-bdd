package scenariogen

import (
	"errors"
	"fmt"
	"github.com/ondatra-ai/true-bdd/services/true-bdd/internal/infrastructure/disk"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

func testMainTarget(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return "", fmt.Errorf("read TestMain directory: %w", err)
	}

	target := ""

	for _, entry := range entries {
		if entry.IsDir() || !goTestSource(entry.Name()) {
			continue
		}

		filename := filepath.Join(dir, entry.Name())

		marked, blocked, readErr := testMainOwnership(filename)
		if readErr != nil {
			return "", readErr
		}

		if blocked {
			return "", nil
		}

		if marked {
			target = filename
		}
	}

	return missingTestMainTarget(dir, target)
}

func missingTestMainTarget(dir, marked string) (string, error) {
	if marked != "" {
		return marked, nil
	}

	target := filepath.Join(dir, "main_test.go")

	_, err := os.Stat(target)
	if errors.Is(err, fs.ErrNotExist) {
		return target, nil
	}

	if err != nil {
		return "", fmt.Errorf("locate TestMain: %w", err)
	}

	return "", nil
}

func testMainOwnership(filename string) (bool, bool, error) {
	source, err := disk.Read(filename)
	if err != nil {
		return false, false, fmt.Errorf("read TestMain: %w", err)
	}

	const legacyMarker = "// Code generated by true-bdd build steps. DO NOT EDIT."

	if hasGeneratedMarker(source) && (filepath.Base(filename) == "main_test.go" ||
		strings.Contains(string(source), legacyMarker)) {
		return true, false, nil
	}

	tree, err := parser.ParseFile(token.NewFileSet(), filename, source, 0)
	if err != nil {
		return false, false, fmt.Errorf("parse TestMain: %w", err)
	}

	for _, declaration := range tree.Decls {
		if fun, ok := declaration.(*ast.FuncDecl); ok && fun.Name.Name == "TestMain" && fun.Recv == nil {
			return hasGeneratedMarker(source), !hasGeneratedMarker(source), nil
		}
	}

	return false, false, nil
}

func goTestSource(name string) bool {
	return !strings.HasPrefix(name, ".") && !strings.HasPrefix(name, "_") && strings.HasSuffix(name, "_test.go")
}
