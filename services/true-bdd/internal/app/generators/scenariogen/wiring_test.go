func wiringPlan(t *testing.T) (*scenariogen.Plan, string) {
	t.Helper()
	root := t.TempDir()

	err := disk.Write(filepath.Join(root, "go.mod"), []byte("module host/root\n"), disk.Private)
	if err != nil {
		t.Fatal(err)
	}
	// The nested module and suite folder deliberately differ from the service name.
	err = disk.Write(filepath.Join(root, "checks/go.mod"), []byte("module host/checks\n"), disk.Private)
	if err != nil {
		t.Fatal(err)
	}

	arch := &architecture.Architecture{
		Testing:  architecture.Testing{Framework: scenariogen.FrameworkGoTest},
		Services: []architecture.Service{{Name: "calc", Path: "services/calc"}},
	}

	plan, err := scenariogen.BuildPlan([]*registry.RegistryScenario{{
		ID: "calc-001", Service: "calc", Path: "checks/arithmetic/calc_test.go",
		Statements: []registry.Statement{{Keyword: registry.KeywordGiven, Text: "a calculator"}},
	}}, arch, root, "docs/scenarios.yaml")
	if err != nil {
		t.Fatal(err)
	}

	return plan, root
}

func TestSuiteWiringRendersTheConfiguredSuite(t *testing.T) {
	t.Parallel()
	plan, root := wiringPlan(t)

	err := scenariogen.WriteWiring(plan, root, "docs/scenarios.yaml", "docs/architecture/architecture.yaml")
	if err != nil {
		t.Fatal(err)
	}

	source, err := disk.Read(filepath.Join(root, "checks/arithmetic/scenarios/scenarios.go"))
	if err != nil {
		t.Fatal(err)
	}

	for _, want := range []string{
		"// Code generated by true-bdd build steps. DO NOT EDIT.",
		"package scenarios", `"host/checks/arithmetic/steps"`,
		`Registry:     "../../docs/scenarios.yaml"`,
		`Architecture: "../../docs/architecture/architecture.yaml"`,
		`Suite:        "calc"`,
		"//nolint:gochecknoglobals // one suite and Registry load per test process",
		"sync.OnceValues(newSuite)",
		"func New(t *testing.T, scenarioID string) *bddgo.Run[steps.State]",
		"suite.Init(func(_ *bddgo.World) (*steps.State, error) { return &steps.State{}, nil })",
		"steps.Register(suite)", "return instance.Scenario(t, scenarioID)",
	} {
		if !strings.Contains(string(source), want) {
			t.Errorf("Suite wiring missing %q:\n%s", want, source)
		}
	}
}

func TestSuiteWiringFollowsAMovedRegistry(t *testing.T) {
	t.Parallel()

	plan, root := wiringPlan(t)
	for _, registryPath := range []string{"docs/scenarios.yaml", filepath.Join(root, "spec/registry.yaml")} {
		err := scenariogen.WriteWiring(plan, root, registryPath, filepath.Join(root, "docs/architecture/architecture.yaml"))
		if err != nil {
			t.Fatal(err)
		}
	}

	source, err := disk.Read(filepath.Join(root, "checks/arithmetic/scenarios/scenarios.go"))
	if err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(string(source), `Registry:     "../../spec/registry.yaml"`) ||
		strings.Contains(string(source), "docs/scenarios.yaml") {
		t.Fatalf("Suite wiring did not follow the configured Registry:\n%s", source)
	}
}

func TestSuiteWiringPreservesAHandWrittenPackage(t *testing.T) {
	t.Parallel()

	for _, name := range []string{"scenarios.go", "custom.go"} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			plan, root := wiringPlan(t)
			target := filepath.Join(root, "checks/arithmetic/scenarios", name)
			// Merely quoting the marker does not make a hand-written package generated.
			original := "package scenarios\nconst marker = `// Code generated by true-bdd build steps. DO NOT EDIT.`\n"

			err := disk.Write(target, []byte(original), disk.Private)
			if err != nil {
				t.Fatal(err)
			}

			err = scenariogen.WriteWiring(plan, root, "docs/scenarios.yaml", "docs/architecture/architecture.yaml")
			if err != nil {
				t.Fatal(err)
			}

			source, err := disk.Read(target)
			if err != nil {
				t.Fatal(err)
			}

			if string(source) != original {
				t.Fatalf("hand-written Suite wiring changed:\n%s", source)
			}

			entries, err := filepath.Glob(filepath.Join(root, "checks/arithmetic/scenarios/*.go"))
			if err != nil {
				t.Fatal(err)
			}

			if len(entries) != 1 {
				t.Fatalf("added source to a hand-written package: %v", entries)
			}
		})
	}
}

func TestSuiteWiringRefreshesItsMarkedFileBesideAHelper(t *testing.T) {
	t.Parallel()
	plan, root := wiringPlan(t)

	err := scenariogen.WriteWiring(plan, root, "docs/scenarios.yaml", "docs/architecture/architecture.yaml")
	if err != nil {
		t.Fatal(err)
	}

	helper := filepath.Join(root, "checks/arithmetic/scenarios/helper.go")
	original := "package scenarios\nconst helper = true\n"

	err = disk.Write(helper, []byte(original), disk.Private)
	if err != nil {
		t.Fatal(err)
	}

	err = scenariogen.WriteWiring(plan, root, "spec/registry.yaml", "docs/architecture/architecture.yaml")
	if err != nil {
		t.Fatal(err)
	}

	source, err := disk.Read(filepath.Join(root, "checks/arithmetic/scenarios/scenarios.go"))
	if err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(string(source), `Registry:     "../../spec/registry.yaml"`) {
		t.Fatalf("marked Suite wiring was not refreshed:\n%s", source)
	}

	source, err = disk.Read(helper)
	if err != nil {
		t.Fatal(err)
	}

	if string(source) != original {
		t.Fatalf("helper changed:\n%s", source)
	}
}
