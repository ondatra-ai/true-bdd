package scenariogen_test

import (
	"path/filepath"
	"strings"
	"testing"

	"github.com/ondatra-ai/true-bdd/services/true-bdd/internal/app/generators/scenariogen"
	"github.com/ondatra-ai/true-bdd/services/true-bdd/internal/infrastructure/architecture"
	"github.com/ondatra-ai/true-bdd/services/true-bdd/internal/infrastructure/disk"
	"github.com/ondatra-ai/true-bdd/services/true-bdd/internal/infrastructure/registry"
)

const wiringService = "calc"

const generatedWiringMarker = "// Code generated by `true-bdd build tests`. DO NOT EDIT."

func wiringPlan(t *testing.T) (*scenariogen.Plan, string) {
	t.Helper()
	root := t.TempDir()

	err := disk.Write(filepath.Join(root, "go.mod"), []byte("module host/root\n"), disk.Private)
	if err != nil {
		t.Fatal(err)
	}
	// The nested module and suite folder deliberately differ from the service name.
	err = disk.Write(filepath.Join(root, "checks/go.mod"), []byte("module host/checks\n"), disk.Private)
	if err != nil {
		t.Fatal(err)
	}

	arch := &architecture.Architecture{
		Testing:  architecture.Testing{Framework: scenariogen.FrameworkGoTest},
		Services: []architecture.Service{{Name: wiringService, Path: "services/calc"}},
	}

	plan, err := scenariogen.BuildPlan([]*registry.RegistryScenario{{
		ID: "calc-001", Service: wiringService, Path: "checks/arithmetic/calc_test.go",
		Statements: []registry.Statement{{Keyword: registry.KeywordGiven, Text: "a calculator"}},
	}}, arch, root, "docs/scenarios.yaml")
	if err != nil {
		t.Fatal(err)
	}

	return plan, root
}

func TestMainFileRendersTheConfiguredPlainSuite(t *testing.T) {
	t.Parallel()
	plan, root := wiringPlan(t)

	err := scenariogen.AddMainFiles(plan, root, "docs/scenarios.yaml", "docs/architecture/architecture.yaml")
	if err != nil {
		t.Fatal(err)
	}

	_, err = scenariogen.Write(plan, root)
	if err != nil {
		t.Fatal(err)
	}

	source, err := disk.Read(filepath.Join(root, "checks/arithmetic/main_test.go"))
	if err != nil {
		t.Fatal(err)
	}

	for _, want := range []string{generatedWiringMarker, "package arithmetic_test", `"host/checks/arithmetic/steps"`,
		`Registry:     "../../docs/scenarios.yaml"`, `Architecture: "../../docs/architecture/architecture.yaml"`,
		`Suite:        "calc"`, "steps.Register(suite)", "func TestMain(m *testing.M)", "func New(t *testing.T,"} {
		if !strings.Contains(string(source), want) {
			t.Errorf("main file missing %q:\n%s", want, source)
		}
	}
}
