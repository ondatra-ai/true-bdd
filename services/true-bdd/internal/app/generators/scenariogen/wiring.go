package scenariogen

import (
	"fmt"
	"go/format"
	"path"
	"path/filepath"
)

const wiringMarker = "// Code generated by `true-bdd build tests`. DO NOT EDIT."

// AddMainFiles includes each suite's main file in the deterministic render plan.
func AddMainFiles(plan *Plan, root, registryPath, architecturePath string) error {
	seen := make(map[string]bool)

	files := append([]PlannedFile(nil), plan.Files...)
	for _, file := range files {
		dir := path.Dir(file.Path)
		if seen[dir] {
			continue
		}

		seen[dir] = true

		target, err := testMainTarget(filepath.Join(root, dir))
		if err != nil {
			return err
		}

		if target == "" {
			continue
		}

		source, err := renderMain(file, plan, filepath.Join(root, dir), root, registryPath, architecturePath)
		if err != nil {
			return err
		}

		relative, err := filepath.Rel(root, target)
		if err != nil {
			return fmt.Errorf("locate main file: %w", err)
		}

		plan.Files = append(plan.Files, PlannedFile{Path: filepath.ToSlash(relative), Source: source})
	}

	return nil
}

func renderMain(file PlannedFile, plan *Plan, dir, root, registryPath, architecturePath string) ([]byte, error) {
	stepsImportPath := path.Join(file.SuiteImportPath, "steps")

	var source string

	if plan.Testkit != nil {
		dependencies := renderDependencies(plan, file.Service)
		source = fmt.Sprintf(harnessWiringSource, wiringMarker, file.Package, stepsImportPath,
			file.Service, dependencies, quoteStrings(plan.Testkit.RepoLayer),
			plan.Testkit.FixtureStep, renderRecordExclude(plan.RecordExclude))
	} else {
		registry, err := relativeDocument(dir, root, registryPath)
		if err != nil {
			return nil, err
		}

		architecture, err := relativeDocument(dir, root, architecturePath)
		if err != nil {
			return nil, err
		}

		source = fmt.Sprintf(wiringSource, wiringMarker, file.Package, stepsImportPath, registry, architecture, file.Service)
	}

	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("render main file: %w", err)
	}

	return formatted, nil
}

func relativeDocument(suiteDir, root, document string) (string, error) {
	if !filepath.IsAbs(document) {
		document = filepath.Join(root, document)
	}

	relative, err := filepath.Rel(suiteDir, document)
	if err != nil {
		return "", fmt.Errorf("locate suite document: %w", err)
	}

	return filepath.ToSlash(relative), nil
}

const wiringSource = `//go:build bdd

%s

package %s

import (
 "fmt"
 "os"
 "sync"
 "testing"

 %q
 "github.com/ondatra-ai/true-bdd/pkg/testkit/bddgo"
)

//nolint:gochecknoglobals // one suite and Registry load per test process
var suite = sync.OnceValues(newSuite)

func newSuite() (*bddgo.Suite[steps.State], error) {
 suite, err := bddgo.New[steps.State](bddgo.Options{
  Registry: %q,
  Architecture: %q,
  Suite: %q,
 })
 if err != nil {
  return nil, fmt.Errorf("build suite: %%w", err)
 }

 suite.Init(func(_ *bddgo.World) (*steps.State, error) { return &steps.State{}, nil })
 steps.Register(suite)

 return suite, nil
}

func TestMain(m *testing.M) { os.Exit(m.Run()) }

// New returns the Scenario's run with fresh state and shared step definitions.
func New(t *testing.T, scenarioID string) *bddgo.Run[steps.State] {
 t.Helper()

 instance, err := suite()
 if err != nil {
  t.Fatal(err)
 }

 return instance.Scenario(t, scenarioID)
}
`

const harnessWiringSource = `//go:build bdd

%s

package %s

import (
 "testing"
 "os"

 "github.com/ondatra-ai/true-bdd/pkg/testkit"
 "github.com/ondatra-ai/true-bdd/pkg/testkit/bddgo"
 proxycli "github.com/ondatra-ai/true-bdd/pkg/proxy/cli"
 %q
)

//nolint:gochecknoglobals // one suite per test binary; the door owns its lifecycle.
var suite = testkit.NewSuite(%q, []proxycli.Dependency{%s},
 func(suite *bddgo.Suite[steps.State]) { steps.Register(suite) },
 func(run *testkit.ScenarioRun) *steps.State { return &steps.State{ScenarioRun: run} },
 testkit.SuiteOptions{RepoLayer: []string{%s}, FixtureStep: %q%s})

func TestMain(m *testing.M) { os.Exit(suite.Main(m)) }

// New selects the Scenario a generated test drives.
func New(t *testing.T, scenarioID string) *bddgo.Run[steps.State] {
 t.Helper()
 return suite.New(t, scenarioID)
}

`
