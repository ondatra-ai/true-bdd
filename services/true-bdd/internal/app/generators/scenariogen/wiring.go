package scenariogen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"

	"github.com/ondatra-ai/true-bdd/services/true-bdd/internal/infrastructure/disk"
)

const wiringMarker = "// Code generated by true-bdd build steps. DO NOT EDIT."

// WriteWiring writes missing Suite wiring and refreshes the engine's own wiring.
// A package without the engine's marker is left unchanged.
func WriteWiring(plan *Plan, repoRoot, registryPath, architecturePath string) error {
	root, err := filepath.Abs(repoRoot)
	if err != nil {
		return fmt.Errorf("locate Suite wiring host: %w", err)
	}

	seen := make(map[string]bool)

	for _, file := range plan.Files {
		suiteDir := filepath.Join(root, filepath.FromSlash(path.Dir(file.Path)))
		if seen[suiteDir] {
			continue
		}

		seen[suiteDir] = true

		err = writeWiring(file, suiteDir, root, registryPath, architecturePath)
		if err != nil {
			return err
		}
	}

	return nil
}

func writeWiring(file PlannedFile, suiteDir, root, registryPath, architecturePath string) error {
	target, err := wiringTarget(filepath.Join(suiteDir, scenariosPkgDir))
	if err != nil || target == "" {
		return err
	}

	registry, err := relativeDocument(suiteDir, root, registryPath)
	if err != nil {
		return err
	}

	architecture, err := relativeDocument(suiteDir, root, architecturePath)
	if err != nil {
		return err
	}

	source, err := format.Source([]byte(fmt.Sprintf(wiringSource, wiringMarker,
		strings.TrimSuffix(file.ScenariosPkg, "/"+scenariosPkgDir)+"/steps", registry, architecture, file.Service)))
	if err != nil {
		return fmt.Errorf("render Suite wiring: %w", err)
	}

	previous, err := disk.Read(target)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("read Suite wiring: %w", err)
	}

	if bytes.Equal(source, previous) {
		return nil
	}

	err = disk.Write(target, source, disk.Shared)
	if err != nil {
		return fmt.Errorf("write Suite wiring: %w", err)
	}

	return nil
}

func relativeDocument(suiteDir, root, document string) (string, error) {
	if !filepath.IsAbs(document) {
		document = filepath.Join(root, document)
	}

	relative, err := filepath.Rel(suiteDir, document)
	if err != nil {
		return "", fmt.Errorf("locate Suite wiring document: %w", err)
	}

	return filepath.ToSlash(relative), nil
}

// wiringTarget finds the engine's file, preserving unmarked packages whatever their filenames.
func wiringTarget(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return "", fmt.Errorf("read Suite wiring directory: %w", err)
	}

	target := ""
	hasGo := false

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}

		hasGo = true
		filename := filepath.Join(dir, entry.Name())

		source, readErr := disk.Read(filename)
		if readErr != nil {
			return "", fmt.Errorf("read Suite wiring: %w", readErr)
		}

		if ownsWiring(source) {
			target = filename
		}
	}

	if target == "" && !hasGo {
		target = filepath.Join(dir, "scenarios.go")
	}

	return target, nil
}

func ownsWiring(source []byte) bool {
	for line := range strings.SplitSeq(string(source), "\n") {
		line = strings.TrimSpace(line)
		if line == wiringMarker {
			return true
		}

		if line != "" && !strings.HasPrefix(line, "//") {
			return false
		}
	}

	return false
}

const wiringSource = `%s

package scenarios

import (
 "fmt"
 "sync"
 "testing"

 %q
 "github.com/ondatra-ai/true-bdd/pkg/testkit/bddgo"
)

//nolint:gochecknoglobals // one suite and Registry load per test process
var suite = sync.OnceValues(newSuite)

func newSuite() (*bddgo.Suite[steps.State], error) {
 suite, err := bddgo.New[steps.State](bddgo.Options{
  Registry: %q,
  Architecture: %q,
  Suite: %q,
 })
 if err != nil {
  return nil, fmt.Errorf("build suite: %%w", err)
 }

 suite.Init(func(_ *bddgo.World) (*steps.State, error) { return &steps.State{}, nil })
 steps.Register(suite)

 return suite, nil
}

// New returns the Scenario's run with fresh state and shared step definitions.
func New(t *testing.T, scenarioID string) *bddgo.Run[steps.State] {
 t.Helper()

 instance, err := suite()
 if err != nil {
  t.Fatal(err)
 }

 return instance.Scenario(t, scenarioID)
}
`
